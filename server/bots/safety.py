"""Defence/safety model for T2 `FaanBot` (docs/04-bots.md §5). Read that section's own
docstring-equivalent (the doc prose itself) before touching this module -- it is unusually
explicit about *why* riichi-derived safety heuristics don't transfer to Hong Kong rules, and
this module is written to respect that, not to port a riichi safety table.

**Hand-tuned, not trained -- an explicit scope decision, not a silent under-delivery.**
docs/04-bots.md §5 suggests "a logistic regression over these features, trained on self-play
logs, beats hand-tuned weights" and says this "matters more here than in riichi ports." A
trained model needs a labelled corpus of `(features at discard time, did this tile deal in)`
pairs; the only available source is self-play generated by this sub-task itself (docs/06-ml.md
§3: "there is no Hong Kong equivalent of the Tenhou corpus"), which means bootstrapping off a
bot that doesn't have a safety model yet to label danger against, then re-training once one
exists -- a real project in its own right (generate self-play logs, extract per-discard
features, fit and validate a model, re-integrate), not a same-sub-task extension of this file.
The hand-tuned weights below are chosen so each signal moves the score in the *direction* the
doc's reasoning demands (weak/never-zero for genbutsu and suji, hard-zero for no-chance, an
explicit multiplier for meld/tempo/wall reads) and are unit-tested per-signal
(`tests/test_safety.py`) for exactly that direction, not for calibrated real-world accuracy --
**training a real logistic-regression model on self-play logs is flagged here as the natural
follow-up**, not deferred silently.

**The mistake this module is written to avoid: no `is_safe(tile) -> bool`.** Every signal below
is a multiplier on an assumed-danger baseline rate, combined multiplicatively into
`deal_in_probability` -- a float in `[0, 1]`, never a boolean "safe" verdict, except for
`no_chance` itself, which *is* correctly modeled as a hard zero (docs/04-bots.md §5 item 3: "a
hard constraint... unlike 1-2"). Genbutsu and suji only ever scale the estimate down, never to
exactly zero, matching "no furiten, so that guarantee does not exist here."
"""

from __future__ import annotations

from collections.abc import Sequence
from statistics import fmean

from app.views import SeatView
from bots.features import is_terminal_or_honor, seen34
from mahjong_core.tiles import TileId, TileType, tile_id_type

__all__ = [
    "deal_in_probability",
    "expected_cost",
    "is_genbutsu",
    "no_chance",
    "opponent_threat_level",
    "tile_risk",
]

_HONOR_START = 27
_RANKS_PER_SUIT = 9
_DRAGON_TYPES = frozenset(
    {int(TileType.DRAGON_RED), int(TileType.DRAGON_GREEN), int(TileType.DRAGON_WHITE)}
)

# --- tunable weights (hand-tuned, see module docstring) --------------------------------------

_BASE_RATE = 0.06
"""Flat prior P(this specific tile type deals in to one opponent) before any signal below
adjusts it -- deliberately not calibrated to a real observed rate (no self-play safety corpus
exists yet, see module docstring); sized so the multipliers below move it across a believable
0-0.3-ish range rather than saturating at 0 or 1 immediately."""

_ONE_CHANCE_FACTOR = 0.4
"""docs/04-bots.md §5 item 3, the soft half of "one-chance/no-chance": exactly one copy of this
tile type remains unseen. Not a hard constraint (that's `no_chance`, 0 remaining) -- a real
reduction, since only one hidden copy can support a wait on it at all, but still short of proof.
"""

_GENBUTSU_FACTOR = 0.35
"""docs/04-bots.md §5 item 1: "still worth a large likelihood adjustment... just never a hard
safe flag." Weakest-guarantee, highest-volume signal -- the largest reduction here short of
`no_chance`, but never 0."""

_SUJI_FACTOR = 0.75
"""docs/04-bots.md §5 item 2: "weight it below genbutsu" -- a real but much smaller reduction,
since suji's force in riichi comes entirely from furiten, which HK doesn't have."""

_MELD_SUIT_DANGER = 1.4
"""docs/04-bots.md §5 item 4: an opponent with 2+ melds concentrated in one suit is plausibly
Half/Full Flush -- their same-suit tiles get a danger bump, not a safety one."""

_DRAGON_PUNG_DANGER = 1.5
"""docs/04-bots.md §5 item 4: "a dragon pung on the table means the next dragon is expensive."
"""

_TEMPO_THREAT_FACTOR = 1.3
"""docs/04-bots.md §5 item 5: a middle-tile discard right after a string of terminal/honor
discards often marks a hand that just settled into tenpai."""

_WALL_PRESSURE_TIERS: tuple[tuple[int, float], ...] = ((20, 1.5), (40, 1.2))
"""docs/04-bots.md §5 item 6: fewer tiles left -> higher cost per discard. `(remaining_at_or_
below, multiplier)`, checked in order; falls through to 1.0 (no adjustment) with plenty of wall
left."""

_ASSUMED_DEALIN_FAAN = 5.0
"""Baseline assumed faan if this discard deals in, absent any other read on the opponent's hand
value -- an arbitrary-but-documented mid-table value (halfway between `min_faan=3` and a
half-flush-plus-dragon 4-5 faan hand), scaled up by `_meld_value_bump` when melds suggest
something pricier. Used only as a relative cost unit for ranking candidate discards against each
other within one decision, never compared across bots or presented as a real point estimate."""


def no_chance(tile_type: int, seen: Sequence[int]) -> bool:
    """docs/04-bots.md §5 item 3, the hard-constraint half: every copy of `tile_type` is
    already accounted for outside the wall (in some hand, meld, or discard pile), so literally
    no one can complete a wait needing it -- "if all four 3s are visible, nobody has a 4-5 wait
    needing a 3." Tile-count fact, not opponent psychology; unlike every other signal in this
    module, this is allowed to force the probability to exactly 0.
    """
    return seen[tile_type] >= 4


def is_genbutsu(view: SeatView, opponent_seat: int, tile_type: int) -> bool:
    """Whether `tile_type` sits in `opponent_seat`'s own discard pool -- weak evidence in HK
    (module docstring), never treated as a guarantee by any caller here."""
    return any(int(tile_id_type(t)) == tile_type for t in view.discard_pools[opponent_seat])


def _is_suji(view: SeatView, opponent_seat: int, tile_type: int) -> bool:
    """docs/04-bots.md §5 item 2: `tile_type` is a suji of some tile `opponent_seat` already
    discarded (same suit, 3 ranks apart) -- honors have no suit-adjacency, so never suji."""
    if tile_type >= _HONOR_START:
        return False
    suit, rank = divmod(tile_type, _RANKS_PER_SUIT)
    for offset in (-3, 3):
        other_rank = rank + offset
        if 0 <= other_rank < _RANKS_PER_SUIT:
            other_type = suit * _RANKS_PER_SUIT + other_rank
            if is_genbutsu(view, opponent_seat, other_type):
                return True
    return False


def _opponent_suit_meld_counts(view: SeatView, opponent_seat: int) -> dict[int, int]:
    counts: dict[int, int] = {}
    for meld in view.melds[opponent_seat]:
        v = int(meld.tile_type)
        if v < _HONOR_START:
            counts[v // _RANKS_PER_SUIT] = counts.get(v // _RANKS_PER_SUIT, 0) + 1
    return counts


def _opponent_dragon_pung_count(view: SeatView, opponent_seat: int) -> int:
    return sum(1 for m in view.melds[opponent_seat] if int(m.tile_type) in _DRAGON_TYPES)


def _meld_danger_multiplier(view: SeatView, opponent_seat: int, tile_type: int) -> float:
    """docs/04-bots.md §5 item 4 ("meld reading"): visible melds narrowing likely hand shape,
    applied as a danger *multiplier* on the tile types that shape would want, never a
    standalone verdict."""
    multiplier = 1.0
    if tile_type < _HONOR_START:
        suit = tile_type // _RANKS_PER_SUIT
        suit_melds = _opponent_suit_meld_counts(view, opponent_seat)
        if suit_melds.get(suit, 0) >= 2:
            multiplier *= _MELD_SUIT_DANGER
    if tile_type in _DRAGON_TYPES and _opponent_dragon_pung_count(view, opponent_seat) >= 1:
        multiplier *= _DRAGON_PUNG_DANGER
    return multiplier


def _tempo_multiplier(pool: Sequence[TileId]) -> float:
    """docs/04-bots.md §5 item 5: a sudden middle-tile discard after a string of terminal/honor
    discards. Needs at least 3 prior discards to call an established "tempo" at all; with fewer,
    there's nothing to detect a change from."""
    if len(pool) < 4:
        return 1.0
    *earlier, most_recent = pool
    earlier_terminal_ratio = fmean(is_terminal_or_honor(int(tile_id_type(t))) for t in earlier)
    recent_is_middle = not is_terminal_or_honor(int(tile_id_type(most_recent)))
    if recent_is_middle and earlier_terminal_ratio >= 0.7:
        return _TEMPO_THREAT_FACTOR
    return 1.0


def wall_pressure_multiplier(wall_remaining: int) -> float:
    """docs/04-bots.md §5 item 6: fewer tiles left -> higher cost per discard."""
    for threshold, multiplier in _WALL_PRESSURE_TIERS:
        if wall_remaining <= threshold:
            return multiplier
    return 1.0


def deal_in_probability(view: SeatView, opponent_seat: int, tile_type: int) -> float:
    """`P(deal_in | tile)` against one opponent -- every signal in docs/04-bots.md §5 folded
    into one `[0, 1]` estimate, `no_chance` aside the only hard override. Order of application
    doesn't matter (everything after the `no_chance` check is a multiplicative scale), but
    genbutsu/suji are mutually exclusive checks (suji only evaluated when genbutsu doesn't
    already apply) since genbutsu is the strictly stronger read when both would otherwise fire.
    """
    seen = seen34(view)
    if no_chance(tile_type, seen):
        return 0.0

    p = _BASE_RATE
    live = 4 - seen[tile_type]
    if live == 1:
        p *= _ONE_CHANCE_FACTOR

    if is_genbutsu(view, opponent_seat, tile_type):
        p *= _GENBUTSU_FACTOR
    elif _is_suji(view, opponent_seat, tile_type):
        p *= _SUJI_FACTOR

    p *= _meld_danger_multiplier(view, opponent_seat, tile_type)
    p *= _tempo_multiplier(view.discard_pools[opponent_seat])
    return min(p, 1.0)


def expected_cost(view: SeatView, opponent_seat: int, tile_type: int) -> float:
    """Assumed faan lost if `tile_type` deals into `opponent_seat` right now -- a relative cost
    unit (module docstring), scaled up by meld reads and wall pressure, both of which raise the
    stakes of a deal-in without changing its probability."""
    cost = _ASSUMED_DEALIN_FAAN
    cost *= _meld_danger_multiplier(view, opponent_seat, tile_type)
    cost *= wall_pressure_multiplier(view.wall_remaining)
    return cost


def tile_risk(view: SeatView, tile_type: int) -> float:
    """`P(deal_in | tile) * expected_cost`, summed across every opponent -- the `-deal_in_risk`
    term docs/04-bots.md §4's scoring formula subtracts. Summing rather than the (more strictly
    correct) `1 - prod(1 - p_i)` "at least one" combination is deliberate: at `_BASE_RATE`'s
    small magnitude the two are nearly identical, and a sum keeps each opponent's contribution
    separately inspectable for the unit tests below rather than folded into one product.
    """
    if view.seat is None:
        raise ValueError("tile_risk needs a seated view, not a spectator's")
    total = 0.0
    for opponent in range(4):
        if opponent == view.seat:
            continue
        total += deal_in_probability(view, opponent, tile_type) * expected_cost(
            view, opponent, tile_type
        )
    return total


def opponent_threat_level(view: SeatView, opponent_seat: int) -> float:
    """A coarse "how worried should T2 be about this opponent" score, used by `bots/faanbot.py`'s
    fold logic (docs/04-bots.md §4: "at 3+ shanten on turn 12 against a threatening opponent").
    Combines meld count (more exposed melds -> plausibly close to tenpai) and the tempo signal
    (item 5) -- not a probability, just a threshold-compared scalar."""
    melds = len(view.melds[opponent_seat])
    tempo_bump = _tempo_multiplier(view.discard_pools[opponent_seat]) - 1.0
    return melds * 0.3 + tempo_bump
